import { expect, test } from '@playwright/test';

test('administrator creates and updates a persisted local user', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', message => { if (message.type() === 'error' && !message.text().includes('401')) errors.push(message.text()); });
  const email = process.env.E2E_ADMIN_EMAIL, password = process.env.E2E_ADMIN_PASSWORD;
  if (!email || !password) throw new Error('Set E2E_ADMIN_EMAIL and E2E_ADMIN_PASSWORD to local bootstrap credentials');
  const suffix = `${Date.now()}`;
  const segment = `Users segment ${suffix}`, name = `User ${suffix}`, userEmail = `user${suffix}@example.test`;
  await page.goto('/');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Segments' }).click();
  await page.getByLabel('Name').fill(segment);
  await page.getByLabel('Owner').fill('Owner');
  await page.getByRole('button', { name: 'Create segment' }).click();
  await expect(page.getByText('Segment created.')).toBeVisible();
  await page.getByRole('link', { name: 'Users' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Email', { exact: true }).fill(userEmail);
  await page.getByLabel('Password', { exact: true }).fill('local-user-password-123');
  await page.getByLabel('Segment').selectOption({ label: segment });
  const response = page.waitForResponse(result => result.url().endsWith('/api/v1/users') && result.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create user' }).click();
  expect((await response).status()).toBe(201);
  const row = page.getByRole('row').filter({ hasText: userEmail });
  await expect(row).toContainText(segment);
  await row.getByRole('button', { name: `Edit ${name}` }).click();
  await page.getByLabel('Role').selectOption('auditor');
  await page.getByLabel('Status').selectOption('disabled');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(row).toContainText('disabled');
  await page.reload();
  await expect(page.getByRole('row').filter({ hasText: userEmail })).toContainText('auditor');
  await expect(page.getByRole('row').filter({ hasText: userEmail })).toContainText('disabled');
  expect(errors).toEqual([]);
});
