import { expect, test } from './fixtures';

test('administrator creates, searches and edits a persisted application', async ({ page }) => {
  const email = process.env.E2E_ADMIN_EMAIL;
  const password = process.env.E2E_ADMIN_PASSWORD;
  if (!email || !password) throw new Error('Set E2E_ADMIN_EMAIL and E2E_ADMIN_PASSWORD to local bootstrap credentials');
  const suffix = `${Date.now()}`;
  const segment = `Segment ${suffix}`, name = `Application ${suffix}`;
  await page.goto('/');
  await page.getByLabel('Email').fill(email);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in' }).click();
  await page.getByRole('link', { name: 'Segments' }).click();
  await page.getByLabel('Name').fill(segment);
  await page.getByLabel('Owner').fill('Segment owner');
  await page.getByRole('button', { name: 'Create segment' }).click();
  await expect(page.getByText('Segment created.')).toBeVisible();
  await page.getByRole('link', { name: 'Applications' }).click();
  await page.getByLabel('Name', { exact: true }).fill(name);
  await page.getByLabel('Segment', { exact: true }).selectOption({ label: segment });
  await page.getByLabel('Owner', { exact: true }).fill('Original owner');
  await page.getByLabel('Lifecycle').selectOption('Production');
  await page.getByLabel('Criticality').selectOption('High');
  const response = page.waitForResponse(result => result.url().endsWith('/api/v1/applications') && result.request().method() === 'POST');
  await page.getByRole('button', { name: 'Create application' }).click();
  expect((await response).status()).toBe(201);
  await page.getByLabel('Search applications or owners').fill(name);
  const row = page.getByRole('row').filter({ hasText: name });
  await expect(row).toContainText('Original owner');
  await row.getByRole('button', { name: `Edit ${name}` }).click();
  await page.getByLabel('Owner', { exact: true }).fill('Updated owner');
  await page.getByRole('button', { name: 'Save changes' }).click();
  await expect(row).toContainText('Updated owner');
  await page.reload();
  await expect(page.getByRole('row').filter({ hasText: name })).toContainText('Updated owner');
});
